#!/usr/bin/env python3
"""
data/raw_company_analysis.json (구글 폼 "기업분석" 응답)을 종목별로 "최신 1건만" 골라서
stock-atlas-source/app/company-analysis-data.ts 로 내보낸다.

이슈 타임라인(issues-data.ts)과 다르게, 기업분석은 쌓이지 않고 종목당 딱 하나만
유지된다 — 같은 종목에 대해 폼을 다시 제출하면 예전 내용을 "교체"한다 (최신 타임스탬프
기준). 퍼플렉시티/지피티로 분석한 내용을 종목마다 그때그때 올리는 용도.

사용법:
    python scripts/build_company_analysis.py
"""
import json
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW_PATH = ROOT / "data" / "raw_company_analysis.json"
SITE_TS_PATH = ROOT / "stock-atlas-source" / "app" / "company-analysis-data.ts"

TS_HEADER = """// Generated by scripts/build_company_analysis.py on {date}
// 이 파일은 자동 생성됩니다 — 직접 수정하지 말고 구글 폼(유형=기업분석) 응답을 통해 갱신하세요.
export type AnalysisDirection = "긍정" | "중립" | "부정";
export type CompanyAnalysis = {{
  headline: string;
  body: string;
  direction: AnalysisDirection;
  url: string | null;
  updated_at: string;
}};

export const companyAnalysisByStock: Record<string, CompanyAnalysis> = """


def load_json(path: Path, default):
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return default


def main():
    raw_items = load_json(RAW_PATH, [])

    if not SITE_TS_PATH.parent.exists():
        print(f"⚠️ {SITE_TS_PATH.parent} 폴더가 없어서 company-analysis-data.ts 생성을 건너뜁니다.")
        return

    # raw_items는 구글 시트 행 순서 그대로라, 폼 제출 순서(=시간순)와 항상 같다.
    # 그래서 타임스탬프 문자열을 직접 비교할 필요 없이, 그냥 뒤에서 만난 행으로
    # 덮어쓰기만 하면 "종목당 최신 1건"이 자동으로 맞게 된다 (타임스탬프 표기가
    # 로케일에 따라 달라져도 — 예: "2026. 10. 20 오전 10:05:28" — 영향받지 않음).
    latest_by_company: dict[str, dict] = {}
    for item in raw_items:
        latest_by_company[item["company"]] = item

    by_company: dict[str, dict] = {}
    for company, item in latest_by_company.items():
        by_company[company] = {
            "headline": item["title"],
            "body": item["body"],
            "direction": item["direction"],
            "url": item.get("url"),
            "updated_at": item.get("timestamp_date") or datetime.now().strftime("%Y-%m-%d"),
        }

    today = datetime.now().strftime("%Y-%m-%d")
    body = json.dumps(by_company, ensure_ascii=False, indent=2)
    SITE_TS_PATH.write_text(TS_HEADER.format(date=today) + body + ";\n", encoding="utf-8")
    print(f"company-analysis-data.ts 생성 완료 (종목 {len(by_company)}개) → {SITE_TS_PATH}")


if __name__ == "__main__":
    main()
