#!/usr/bin/env python3
"""
data/raw_watchlist.json (구글 폼 "관심종목" 응답)을 종목별로 "최신 1건만" 골라서
stock-atlas-source/app/watchlist-data.ts 로 내보낸다.

기업분석 메모와 비슷하게 종목당 최신 1건만 유지되지만(같은 종목을 다시 올리면
예전 내용을 교체), 표시 위치가 다르다 — 이건 특정 종목 상세 페이지가 아니라
첫 화면(홈)에 "지금 관심있게 보고 있는 종목들" 목록으로 한꺼번에 보여준다.

쌓아두고 지우는 개념이 아니라, 올려둔 종목들이 그대로 목록이 된다(성혁님 요청:
"올리는 것만.. 굳이 누적으로 안 쌓여도 됨"). 같은 종목을 다시 올리면 그 자리가
최신 내용으로 바뀌면서 목록 맨 위로 올라온다(최근 올린 순 정렬).

사용법:
    python scripts/build_watchlist.py
"""
import json
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW_PATH = ROOT / "data" / "raw_watchlist.json"
SITE_TS_PATH = ROOT / "stock-atlas-source" / "app" / "watchlist-data.ts"

TS_HEADER = """// Generated by scripts/build_watchlist.py on {date}
// 이 파일은 자동 생성됩니다 — 직접 수정하지 말고 구글 폼(유형=관심종목) 응답을 통해 갱신하세요.
export type WatchlistDirection = "긍정" | "중립" | "부정";
export type WatchlistItem = {{
  name: string;
  stockCode: string;
  sector: string;
  headline: string;
  body: string;
  direction: WatchlistDirection;
  url: string | null;
  updatedAt: string;
}};

export const watchlist: WatchlistItem[] = """


def load_json(path: Path, default):
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return default


def main():
    raw_items = load_json(RAW_PATH, [])

    if not SITE_TS_PATH.parent.exists():
        print(f"⚠️ {SITE_TS_PATH.parent} 폴더가 없어서 watchlist-data.ts 생성을 건너뜁니다.")
        return

    # raw_items는 구글 시트 행 순서 그대로(=폼 제출 순서=시간순)라, 종목당 최신 값으로
    # 덮어쓰되, 다시 올라온 종목은 목록 맨 뒤(=가장 최근)로 위치를 옮긴다.
    # (딕셔너리에서 키를 지웠다가 다시 넣으면 그 키가 맨 뒤로 이동하는 성질을 이용)
    latest_by_company: dict[str, dict] = {}
    for item in raw_items:
        latest_by_company.pop(item["company"], None)
        latest_by_company[item["company"]] = item

    today = datetime.now().strftime("%Y-%m-%d")
    watchlist = []
    for item in reversed(list(latest_by_company.values())):  # 최근 올린 순으로 정렬
        watchlist.append({
            "name": item["company"],
            "stockCode": item["stock_code"],
            "sector": item["sector"],
            "headline": item["title"],
            "body": item["body"],
            "direction": item["direction"],
            "url": item.get("url"),
            "updatedAt": item.get("timestamp_date") or today,
        })

    body = json.dumps(watchlist, ensure_ascii=False, indent=2)
    SITE_TS_PATH.write_text(TS_HEADER.format(date=today) + body + ";\n", encoding="utf-8")
    print(f"watchlist-data.ts 생성 완료 (관심종목 {len(watchlist)}개) → {SITE_TS_PATH}")


if __name__ == "__main__":
    main()
