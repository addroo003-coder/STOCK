import { readFile, writeFile } from "node:fs/promises";

const UPDATED_AT = "2026-08-27";
const RESEARCH_URL = "https://finance.naver.com/research/company_list.naver";
const NEWS_URL = "https://m.stock.naver.com/api/news/stock";

async function fetchWithRetry(url, attempts = 3) {
  let lastError;
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    try {
      const response = await fetch(url, {
        headers: {
          accept: "text/html,application/json",
          "user-agent": "Mozilla/5.0 (compatible; GrowthAtlas/1.0)",
        },
      });
      if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
      return response;
    } catch (error) {
      lastError = error;
      await new Promise((resolve) => setTimeout(resolve, 500 * attempt));
    }
  }
  throw lastError;
}

async function parallelMap(items, limit, mapper) {
  const output = new Array(items.length);
  let cursor = 0;
  async function worker() {
    while (cursor < items.length) {
      const index = cursor;
      cursor += 1;
      try {
        output[index] = await mapper(items[index], index);
      } catch (error) {
        output[index] = { ...items[index], error: String(error) };
      }
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return output;
}

function decodeEntities(value = "") {
  return value
    .replaceAll("&quot;", '"')
    .replaceAll("&#39;", "'")
    .replaceAll("&amp;", "&")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replace(/<[^>]+>/g, "")
    .trim();
}

function parseReport(html, code) {
  const compact = html.replace(/\s+/g, " ");
  const escapedCode = code.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const pattern = new RegExp(
    `<tr>.*?code=${escapedCode}[^>]*>.*?<\\/a>.*?<td><a href="([^"]*company_read[^"]*)">([^<]+)<\\/a><\\/td>\\s*<td>([^<]+)<\\/td>\\s*<td class="file">\\s*<a href="([^"]+)"[^>]*>.*?<td class="date"[^>]*>([^<]+)<\\/td>`,
  );
  const match = compact.match(pattern);
  if (!match) return null;
  const readUrl = new URL(match[1], RESEARCH_URL).toString();
  return {
    title: decodeEntities(match[2]),
    broker: decodeEntities(match[3]),
    pdfUrl: match[4],
    url: readUrl,
    date: match[5].trim(),
  };
}

function newsScore(article, company) {
  const title = decodeEntities(article.title);
  let score = 0;
  if (title.replaceAll(" ", "").includes(company.replaceAll(" ", ""))) score += 10;
  if (/실적|수주|계약|증설|양산|승인|허가|임상|출시|공급|매출|영업이익|투자|HBM|AI|로봇|원전|ESS/.test(title)) score += 4;
  if (/코스피|코스닥|증시|ETF|외국인|개미|장중|특징주|급등|급락/.test(title) && !title.includes(company)) score -= 5;
  return score;
}

function pickNews(payload, company) {
  const articles = payload.flatMap((group) => group.items ?? []);
  const ranked = articles
    .map((article, index) => ({ article, index, score: newsScore(article, company) }))
    .sort((a, b) => b.score - a.score || a.index - b.index);
  const article = ranked[0]?.article;
  if (!article) return null;
  return {
    title: decodeEntities(article.title),
    office: article.officeName,
    date: article.datetime?.slice(0, 8) ?? "",
    url: `https://n.news.naver.com/mnews/article/${article.officeId}/${article.articleId}`,
  };
}

const earningsSource = await readFile(new URL("../app/earnings-data.ts", import.meta.url), "utf8");
const companies = [...earningsSource.matchAll(/"company": "([^"]+)",\n\s+"code": "([0-9]+)"/g)]
  .map((match) => ({ company: match[1], code: match[2] }));

const uniqueCompanies = [...new Map(companies.map((item) => [item.company, item])).values()];

const results = await parallelMap(uniqueCompanies, 16, async ({ company, code }) => {
  const researchPage = `${RESEARCH_URL}?searchType=itemCode&itemCode=${code}`;
  const newsPage = `${NEWS_URL}/${code}?page=1&pageSize=12`;
  const [researchResponse, newsResponse] = await Promise.all([
    fetchWithRetry(researchPage),
    fetchWithRetry(newsPage),
  ]);
  const researchBuffer = await researchResponse.arrayBuffer();
  const researchHtml = new TextDecoder("euc-kr").decode(researchBuffer);
  const newsPayload = await newsResponse.json();
  return {
    company,
    code,
    updatedAt: UPDATED_AT,
    report: parseReport(researchHtml, code),
    reportListUrl: researchPage,
    news: pickNews(newsPayload, company),
    newsListUrl: `https://m.stock.naver.com/domestic/stock/${code}/news`,
  };
});

const records = Object.fromEntries(results.map((record) => [record.company, record]));
const output = `// Generated by scripts/update-market-sources.mjs on ${UPDATED_AT}.\n` +
  `export type BrokerReport = { title: string; broker: string; date: string; url: string; pdfUrl: string };\n` +
  `export type StockNews = { title: string; office: string; date: string; url: string };\n` +
  `export type MarketSourceRecord = { company: string; code: string; updatedAt: string; report: BrokerReport | null; reportListUrl: string; news: StockNews | null; newsListUrl: string; error?: string };\n\n` +
  `export const marketSourcesByStock: Record<string, MarketSourceRecord> = ${JSON.stringify(records, null, 2)};\n`;

await writeFile(new URL("../app/market-sources.ts", import.meta.url), output);

